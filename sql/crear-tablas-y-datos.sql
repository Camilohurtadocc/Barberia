\connect barberia_auth

CREATE TABLE IF NOT EXISTS usuarios (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   varchar(255) NOT NULL UNIQUE,
    password   varchar(255) NOT NULL,  -- hash BCrypt ($2a$10$...)
    rol        varchar(255),           -- ADMIN o BARBERO
    nombre     varchar(255),
    barbero_id bigint                  -- solo en cuentas BARBERO
);

-- Las contrasenas van aqui en texto plano porque SQL no puede generar un hash
-- BCrypt: el algoritmo vive en la aplicacion. No es un descuido, es el mecanismo:
-- al arrancar, PasswordMigrationRunner detecta las que no empiezan por '$2' y las
-- convierte a BCrypt. En la tabla acaban cifradas igualmente.
INSERT INTO usuarios (username, password, rol, nombre, barbero_id)
SELECT * FROM (VALUES
    ('admin',    'admin123',    'ADMIN',   'Administrador',   CAST(NULL AS BIGINT)),
    ('marcos',   'marcos123',   'BARBERO', 'Marcos Villegas', CAST(1 AS BIGINT)),
    ('santiago', 'santiago123', 'BARBERO', 'Santiago Ríos',   CAST(2 AS BIGINT)),
    ('diego',    'diego123',    'BARBERO', 'Diego Castillo',  CAST(3 AS BIGINT))
) AS v(username, password, rol, nombre, barbero_id)
WHERE NOT EXISTS (SELECT 1 FROM usuarios);
