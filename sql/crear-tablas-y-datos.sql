\connect barberia_citas

CREATE TABLE IF NOT EXISTS citas (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_nombre   varchar(255) NOT NULL,
    cliente_telefono varchar(255) NOT NULL,
    servicio_id      bigint       NOT NULL,
    barbero_id       bigint,        -- columna por la que se filtra "mi agenda"
    barbero          varchar(255),  -- nombre copiado, solo para mostrar
    fecha_hora       timestamp(6) NOT NULL,
    notas            varchar(500),
    estado           varchar(255)   -- PENDIENTE, CONFIRMADA, COMPLETADA, CANCELADA
);

-- servicio_id y barbero_id NO tienen clave foranea a proposito: viven en OTRAS
-- bases de datos (barberia_servicios y barberia_barberos). Es el precio del
-- patron database-per-service; la integridad la valida la aplicacion.


